// 현재 UI 상태에서 입력을 얼마나 차단할지 나타냅니다.
// 실제 입력 시스템은 이 값을 보고 게임플레이 입력을 받을지 말지 판단하면 됩니다.
public enum UIInputBlockType
{
    // 아무 입력도 차단하지 않습니다.
    // InGame 상태에서 팝업이나 오버레이가 없을 때 사용합니다.
    None = 0,

    // 이동, 공격, 점프 같은 게임플레이 입력만 차단합니다.
    // 메뉴 버튼, 팝업 버튼, 컷씬 건너뛰기 입력처럼 UI 입력은 계속 받을 수 있습니다.
    GameplayOnly,

    // 모든 입력을 무시합니다.
    // 로딩 화면처럼 사용자가 아무것도 조작하면 안 되는 상태에 사용합니다.
    All
}
