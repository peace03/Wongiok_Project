// 기본 화면 위에 올라오는 차단형 UI 상태입니다.
// Overlay는 화면 전체를 바꾸지는 않지만, 게임플레이 입력을 막는 UI를 의미합니다.
public enum UIOverlayState
{
    // 현재 열려 있는 Overlay가 없는 상태입니다.
    None = 0,

    // 인게임 영상 컷씬 UI입니다.
    // 기존 대사창 기획은 폐기되었고, 컷씬 재생 중에는 게임플레이 입력을 막습니다.
    Cutscene,

    // 레벨업 보상 선택 UI입니다.
    // 카드 선택 입력만 받고 이동, 공격 같은 게임플레이 입력은 막습니다.
    LevelUp,

    // 일시정지 메뉴 UI입니다.
    // 메뉴 입력만 받고 게임플레이 입력과 게임 시간을 멈춥니다.
    Pause
}
